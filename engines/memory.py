def store_precedent(
    result: InvestigationResult,
    chroma_client: Any,
    llm_provider: LLMProvider,
    db_conn: Any = None,  # reserved for future Postgres persistence; unused in MVP
    outcome_type: OutcomeType = OutcomeType.OBSERVED,
) -> bool:
    """
    Module-level convenience wrapper around MemoryEngine.store_precedent.

    Parameters
    ----------
    result        : Completed InvestigationResult to persist.
    chroma_client : chromadb.Client instance.
    llm_provider  : LLMProvider for embedding and summarization.
    db_conn       : Optional database connection (reserved; not used in MVP).
    outcome_type  : OutcomeType (OBSERVED or SIMULATED).

    Returns True on success, False after retries are exhausted (Req 15.2).

    Requirements: 15.1, 15.2
    """
    engine = MemoryEngine(chroma_client=chroma_client, llm_provider=llm_provider)
    return engine.store_precedent(result, outcome_type=outcome_type)


def retrieve_precedents(
    scenario_id: str,
    query_context: str,
    chroma_client: Any,
    llm_provider: LLMProvider,
    include_simulated: bool = False,
) -> list[dict]:
    """
    Module-level convenience wrapper around MemoryEngine.retrieve_precedents.

    Parameters
    ----------
    scenario_id   : ID of the scenario being investigated.
    query_context : Optional enriching context for the vector query.
    chroma_client : chromadb.Client instance.
    llm_provider  : LLMProvider for embedding.
    include_simulated : If True, includes SIMULATED outcomes (default False).

    Returns a list of precedent dicts sorted by retrieval_score descending.
    Returns [] with a log indication when no relevant precedents are found
    (Req 15.4).

    Requirements: 15.3, 15.4, 15.5
    """
    engine = MemoryEngine(chroma_client=chroma_client, llm_provider=llm_provider)
    return engine.retrieve_precedents(
        scenario_id,
        query_context,
        include_simulated=include_simulated,
    )
